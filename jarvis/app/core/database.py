"""Database connections for JARVIS repositories.

PostgreSQL is opt-in via JARVIS_DATABASE_URL. Existing installations keep
using their SQLite file. All repositories use the same configured database.
"""
from __future__ import annotations

import os
import re
import sqlite3


def postgres_enabled() -> bool:
    return bool(os.environ.get("JARVIS_DATABASE_URL", "").strip())


class _Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [column.name for column in (cursor.description or ())]
    return lambda values: _Row(zip(names, values))


class _PostgresConnection:
    def __init__(self, url: str):
        import psycopg
        self._connection = psycopg.connect(url, row_factory=_row_factory)

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type is None:
                self._connection.commit()
            else:
                self._connection.rollback()
        finally:
            self._connection.close()

    def execute(self, query, params=()):
        normalized = query.strip()
        if re.fullmatch(r"PRAGMA foreign_keys\s*=\s*ON", normalized, re.I):
            return self._connection.execute("SELECT 1 WHERE FALSE")
        column_info = re.fullmatch(r"PRAGMA table_info\((\w+)\)", normalized, re.I)
        if column_info:
            return self._connection.execute(
                "SELECT column_name AS name FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = %s", (column_info[1],)
            )
        if re.fullmatch(r"SELECT\s+name\s+FROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'", normalized, re.I):
            query = "SELECT tablename AS name FROM pg_catalog.pg_tables WHERE schemaname = current_schema()"
        query = re.sub(r"INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", query, flags=re.I)
        query = query.replace("display_name TEXT NOT NULL COLLATE NOCASE UNIQUE", "display_name TEXT NOT NULL UNIQUE")
        query = query.replace("iot_devices(name COLLATE NOCASE)", "iot_devices(lower(name))")
        query = re.sub(r"(\w+)\s*=\s*\?\s+COLLATE NOCASE", r"lower(\1) = lower(?)", query, flags=re.I)
        query = re.sub(r"ORDER BY name COLLATE NOCASE", "ORDER BY lower(name)", query, flags=re.I)
        if re.match(r"\s*INSERT OR IGNORE\s", query, flags=re.I):
            query = re.sub(r"INSERT OR IGNORE", "INSERT", query, count=1, flags=re.I).rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
        query = query.replace("?", "%s")
        # SQLite stores boolean values as integers; the existing schemas use
        # INTEGER flags on both backends.
        params = tuple(int(value) if isinstance(value, bool) else value for value in params)
        return self._connection.execute(query, params)

    def executescript(self, script):
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)


def connect_database(path):
    url = os.environ.get("JARVIS_DATABASE_URL", "").strip()
    if url:
        if not url.startswith(("postgresql://", "postgres://")):
            raise ValueError("JARVIS_DATABASE_URL must be a PostgreSQL URL")
        return _PostgresConnection(url)
    connection = sqlite3.connect(path)
    connection.row_factory = sqlite3.Row
    return connection
